func doctorCommand() error {
	root, m, err := findPad(".")
	if err != nil {
		return err
	}
	failed := false
	for _, tool := range []string{"git", "docker", "caddy"} {
		if _, err := exec.LookPath(tool); err != nil {
			fmt.Printf("MISSING %s\n", tool)
			failed = true
		} else {
			fmt.Printf("OK %s\n", tool)
		}
	}
	if _, err := exec.LookPath("docker"); err == nil {
		if err := checkDockerAccess(); err != nil {
			fmt.Printf("DOCKER unavailable: %v\n", err)
			failed = true
		}
		if output, err := exec.Command("docker", "buildx", "version").CombinedOutput(); err != nil {
			fmt.Printf("BUILDX unavailable: %s; install Ubuntu's `docker-buildx` package or Docker's `docker-buildx-plugin` package\n", strings.TrimSpace(string(output)))
			failed = true
		}
	}
	for _, r := range sortedRepos(m) {
		if err := prepareRepo(root, r, false); err != nil {
			fmt.Printf("NOT READY %s: %v\n", r.Name, err)
			failed = true
			continue
		}
		fmt.Printf("READY %s\n", r.Name)
	}
	if runtime.GOOS == "linux" {
		for _, r := range m.Repos {
			conn, err := net.Listen("tcp", fmt.Sprintf("127.0.0.1:%d", r.HostPort))
			if err == nil {
				conn.Close()
			} else {
				fmt.Printf("PORT %d in use (expected if app is running)\n", r.HostPort)
			}
		}
	}
	if failed {
		return errors.New("doctor found issues")
	}
	return nil
}

func depsCommand(args []string) error {
	if len(args) != 1 {
		return errors.New("usage: uppr deps check|install")
	}
	if args[0] == "check" {
		missing := false
		for _, tool := range []string{"git", "docker", "caddy", "systemctl"} {
			if _, err := exec.LookPath(tool); err != nil {
				fmt.Println("MISSING", tool)
				missing = true
			} else {
				fmt.Println("OK", tool)
			}
		}
		if missing {
			return errors.New("dependencies missing")
		}
		return nil
	}
	if args[0] != "install" {
		return errors.New("usage: uppr deps check|install")
	}
	if err := requireLinux(); err != nil {
		return err
	}
	if _, err := exec.LookPath("apt-get"); err == nil {
		if err := privileged("apt-get", "install", "-y", "git", "docker.io", "docker-buildx", "caddy"); err != nil {
			return err
		}
		return privileged("systemctl", "enable", "--now", "docker.service")
	}
	if _, err := exec.LookPath("dnf"); err == nil {
		if err := privileged("dnf", "install", "-y", "git", "moby-engine", "caddy"); err != nil {
			return err
		}
		return privileged("systemctl", "enable", "--now", "docker.service")
	}
	return errors.New("automatic dependency installation currently supports apt and dnf; run `uppr deps check` for missing tools")
}

func activeUnit(name string) bool {
	cmd := exec.Command("systemctl", "is-active", "--quiet", name)
	return cmd.Run() == nil
}
func sortedKeys[K ~string, V any](m map[K]V) []K {
	out := make([]K, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}
