import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import crypto from "node:crypto";
import { spawnSync, spawn } from "node:child_process";

export type Repo = {
  name: string;
  url: string;
  branch?: string;
  domain: string;
  host_port: number;
  container_port: number;
};
export type Manifest = { version: number; id: string; repos: Repo[] };
export type Variable = {
  name: string;
  description?: string;
  example?: string;
  required?: boolean;
};
export type Schema = { variables: Variable[] };
export const registryDir =
  process.env.UPPR_REGISTRY_DIR || "/etc/uppr/launchpads.d";
export const unitDir = process.env.UPPR_UNIT_DIR || "/etc/systemd/system";
export const safeName = /^[a-z][a-z0-9-]*$/;
export const envName = /^[A-Za-z_][A-Za-z0-9_]*$/;
export const exists = (p: string) => fs.existsSync(p);
export const sorted = (m: Manifest) =>
  [...m.repos].sort((a, b) => a.name.localeCompare(b.name));
export const repoDir = (root: string, r: Repo) =>
  path.join(root, "repos", r.name);
export const unitName = (m: Manifest, r: Repo) =>
  `uppr-${m.id}-${r.name}.service`;
export const imageName = (m: Manifest, r: Repo) =>
  `uppr-${m.id}-${r.name}:latest`;
export const containerName = (m: Manifest, r: Repo) => `uppr-${m.id}-${r.name}`;
export function fail(s: string): never {
  throw new Error(s);
}
export function json<T>(p: string): T {
  return JSON.parse(fs.readFileSync(p, "utf8")) as T;
}
export function writeAtomic(p: string, body: string, mode = 0o644) {
  const tmp = path.join(
    path.dirname(p),
    `.uppr-${crypto.randomBytes(6).toString("hex")}`,
  );
  try {
    fs.writeFileSync(tmp, body, { mode });
    fs.renameSync(tmp, p);
  } finally {
    if (exists(tmp)) fs.rmSync(tmp);
  }
}
export function loadManifest(root: string): Manifest {
  const m = json<Manifest>(path.join(root, "launchpad.json"));
  if (m.version !== 1 || !safeName.test(m.id) || !Array.isArray(m.repos))
    fail("invalid or unsupported launchpad manifest");
  const names = new Set(),
    ports = new Set(),
    domains = new Set();
  for (const r of m.repos) {
    if (
      !safeName.test(r.name) ||
      !r.url ||
      !validDomain(r.domain) ||
      !validPort(r.host_port) ||
      !validPort(r.container_port) ||
      names.has(r.name) ||
      ports.has(r.host_port) ||
      domains.has(r.domain)
    )
      fail(`invalid or duplicate repo ${r.name}`);
    names.add(r.name);
    ports.add(r.host_port);
    domains.add(r.domain);
  }
  return m;
}
export function findPad(start = process.cwd()): [string, Manifest] {
  let root = path.resolve(start);
  while (true) {
    if (exists(path.join(root, "launchpad.json")))
      return [root, loadManifest(root)];
    let parent = path.dirname(root);
    if (parent === root) fail("launchpad not found; run `uppr init <path>`");
    root = parent;
  }
}
export function saveManifest(root: string, m: Manifest) {
  writeAtomic(
    path.join(root, "launchpad.json"),
    JSON.stringify(m, null, 2) + "\n",
  );
}
export function initPad(dir: string) {
  const root = path.resolve(dir);
  if (exists(path.join(root, "launchpad.json")))
    fail(`${root} is already initialized`);
  fs.mkdirSync(path.join(root, "repos"), { recursive: true });
  fs.mkdirSync(path.join(root, "systemd"), { recursive: true });
  let base = slug(path.basename(root)) || "pad";
  if (!/^[a-z]/.test(base)) base = "pad-" + base;
  saveManifest(root, {
    version: 1,
    id: `${base}-${crypto.randomBytes(4).toString("hex")}`,
    repos: [],
  });
  fs.writeFileSync(path.join(root, ".gitignore"), "/repos/\n");
  fs.writeFileSync(
    path.join(root, "Caddyfile"),
    "# Generated by uppr generate.\n",
  );
  return root;
}
export const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
export const validPort = (v: number) =>
  Number.isInteger(v) && v > 0 && v <= 65535;
export const validDomain = (s: string) =>
  typeof s === "string" &&
  s.length <= 253 &&
  s
    .split(".")
    .every(
      (x) =>
        x.length > 0 &&
        x.length <= 63 &&
        /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(x),
    );
export function select(m: Manifest, name?: string) {
  if (!name) return m.repos;
  const r = m.repos.find((r) => r.name === name);
  if (!r) fail(`unknown repo ${name}`);
  return [r];
}
export function installedPads(): Record<string, { id: string; root: string }> {
  const out: Record<string, { id: string; root: string }> = {};
  if (!exists(registryDir)) return out;
  for (const e of fs.readdirSync(registryDir)) {
    if (!e.endsWith(".json")) continue;
    const p = json<{ id: string; root: string }>(path.join(registryDir, e));
    if (!safeName.test(p.id) || !path.isAbsolute(p.root))
      fail(`invalid registry entry ${e}`);
    out[p.id] = p;
  }
  return out;
}
export function freePort(m: Manifest) {
  const ports = new Set(m.repos.map((r) => r.host_port));
  for (const p of Object.values(installedPads())) {
    try {
      for (const r of loadManifest(p.root).repos) ports.add(r.host_port);
    } catch {}
  }
  for (let n = 20000; n < 60000; n++) if (!ports.has(n)) return n;
  fail("no available host port");
}
export function run(
  cmd: string,
  args: string[] = [],
  opts: {
    cwd?: string;
    env?: NodeJS.ProcessEnv;
    quiet?: boolean;
    input?: string;
  } = {},
) {
  const result = spawnSync(cmd, args, {
    cwd: opts.cwd,
    env: opts.env || process.env,
    encoding: "utf8",
    stdio: opts.quiet ? "pipe" : "inherit",
    input: opts.input,
  });
  if (result.error) fail(`${cmd}: ${result.error.message}`);
  if (result.status !== 0)
    fail(
      `${cmd} ${args.join(" ")} failed${opts.quiet ? `: ${(result.stderr || result.stdout).trim()}` : ""}`,
    );
  return (result.stdout || "").trim();
}
export function probe(cmd: string, args: string[] = [], cwd?: string) {
  const r = spawnSync(cmd, args, { cwd, encoding: "utf8", stdio: "pipe" });
  return {
    ok: r.status === 0,
    out: (r.stdout || "").trim(),
    err: (r.stderr || "").trim(),
  };
}
export function which(cmd: string) {
  const r = probe("which", [cmd]);
  return r.ok ? r.out : "";
}
export function privileged(cmd: string, args: string[] = []) {
  run(
    process.getuid?.() === 0 ? cmd : "sudo",
    process.getuid?.() === 0
      ? args
      : [...(process.env.UPPR_NONINTERACTIVE ? ["-n"] : []), cmd, ...args],
  );
}
export function linux() {
  if (process.platform !== "linux") fail("systemd operations require Linux");
}
export function active(unit: string) {
  return probe("systemctl", ["is-active", "--quiet", unit]).ok;
}
export function serviceState(unit: string) {
  if (process.platform !== "linux" || !which("systemctl")) return "unavailable";
  const load = probe("systemctl", [
    "show",
    "--property=LoadState",
    "--value",
    unit,
  ]);
  if (!load.ok || load.out !== "loaded")
    return load.out === "not-found"
      ? "not installed"
      : load.out || "unavailable";
  const state = probe("systemctl", ["is-active", unit]);
  return state.out || "unknown";
}
export function appStatus(m: Manifest, r: Repo) {
  const service = serviceState(unitName(m, r));
  const docker = which("docker")
    ? probe("docker", [
        "inspect",
        "--format",
        "{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{end}}",
        containerName(m, r),
      ])
    : { ok: false, out: "", err: "" };
  const fields = docker.out.split(/\s+/);
  return {
    service,
    container: docker.ok ? fields[0] : "—",
    health: docker.ok ? fields[1] || "—" : "—",
    state:
      docker.ok && fields[0] === "running"
        ? fields[1] === "unhealthy"
          ? "unhealthy"
          : "running"
        : service === "active"
          ? "starting"
          : service === "inactive"
            ? "stopped"
            : service,
  };
}
export type SetupStep = {
  label: string;
  detail: string;
  action?: string;
};
export function appSetup(
  root: string,
  r: Repo,
  status: ReturnType<typeof appStatus>,
): SetupStep {
  const p = repoDir(root, r);
  if (!exists(p))
    return {
      label: "Needs checkout",
      detail: "Clone the repository to get started.",
      action: "pull",
    };
  if (!exists(path.join(p, "Dockerfile")))
    return {
      label: "Needs Dockerfile",
      detail: "Add a production Dockerfile at the repository root.",
    };
  const schema = schemaPath(root, r);
  if (!exists(schema))
    return {
      label: "Needs schema",
      detail: "Generate a schema from an env example, then review it.",
      action: "schema-generate",
    };
  let variables: Variable[];
  try {
    variables = readSchema(schema).variables;
  } catch (error) {
    return {
      label: "Schema error",
      detail: error instanceof Error ? error.message : String(error),
      action: "schema-edit",
    };
  }
  const env = path.join(p, "config", ".env");
  const values = exists(env) ? readEnv(fs.readFileSync(env, "utf8")) : {};
  const missing = variables
    .filter((v) => v.required !== false && !values[v.name]?.trim())
    .map((v) => v.name);
  if (!exists(env) || missing.length)
    return {
      label: "Needs environment",
      detail: missing.length
        ? `Set ${missing.join(", ")} in config/.env.`
        : "Create config/.env from the schema.",
      action: "env-setup",
    };
  if (status.state === "unhealthy" || status.state === "failed")
    return {
      label: "Needs attention",
      detail: "Inspect the app logs for the failure.",
      action: "logs",
    };
  if (process.platform !== "linux")
    return {
      label: "Ready for Linux",
      detail: "Run installation and serving commands on a Linux host.",
    };
  if (status.service === "not installed" || status.service === "unavailable")
    return {
      label: "Needs install",
      detail: "Install the launchpad's services and routes.",
      action: "install",
    };
  if (status.state !== "running")
    return {
      label: "Ready to serve",
      detail: "Build and start the app.",
      action: "serve",
    };
  return {
    label: "Running",
    detail: "The app is running. Open its route or inspect logs.",
  };
}
export function schemaPath(root: string, r: Repo) {
  return path.join(repoDir(root, r), "schema.json");
}
export function validateSchema(s: Schema) {
  if (!s || !Array.isArray(s.variables))
    fail("schema.json needs a variables array");
  const names = new Set();
  for (const v of s.variables) {
    if (!envName.test(v.name) || names.has(v.name))
      fail(`invalid or duplicate schema variable ${v.name}`);
    names.add(v.name);
    if (v.required !== undefined && typeof v.required !== "boolean")
      fail(`${v.name}: required must be boolean`);
  }
  return s;
}
export function readSchema(p: string) {
  return validateSchema(json<Schema>(p));
}
export function saveSchema(p: string, s: Schema) {
  validateSchema(s);
  writeAtomic(p, JSON.stringify(s, null, 2) + "\n");
}
export function readEnv(content: string) {
  const values: Record<string, string> = {};
  for (let line of content.split("\n")) {
    line = line.trim();
    if (!line || line.startsWith("#")) continue;
    const i = line.indexOf("=");
    if (i < 0) continue;
    values[line.slice(0, i).trim()] = line
      .slice(i + 1)
      .trim()
      .replace(/^['"]|['"]$/g, "");
  }
  return values;
}
export function setEnv(content: string, key: string, value: string) {
  const lines = content.split("\n");
  let found = false;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].trim().split("=")[0].trim() === key) {
      lines[i] = `${key}=${value}`;
      found = true;
    }
  }
  return found
    ? lines.join("\n")
    : (content && !content.endsWith("\n") ? content + "\n" : content) +
        `${key}=${value}\n`;
}
export function saveRepoEnv(
  root: string,
  r: Repo,
  updates: Record<string, string>,
) {
  const p = repoDir(root, r);
  if (!exists(path.join(p, "Dockerfile")))
    fail(`${r.name}: Dockerfile is missing; run uppr pull ${r.name}`);
  if (exists(path.join(p, ".git"))) {
    const tracked = probe("git", ["ls-files", "--", "config", "data"], p);
    if (!tracked.ok) fail(tracked.err);
    if (tracked.out)
      fail(`${r.name}: protected files tracked by Git: ${tracked.out}`);
  }
  const schema = readSchema(schemaPath(root, r));
  const names = new Set(schema.variables.map((v) => v.name));
  const env = path.join(p, "config", ".env");
  let content = exists(env) ? fs.readFileSync(env, "utf8") : "";
  for (const [name, value] of Object.entries(updates)) {
    if (!names.has(name)) fail(`${name} is not in ${r.name}/schema.json`);
    if (/[\r\n\0]/.test(value)) fail(`${name} contains a control character`);
    content = setEnv(content, name, value);
  }
  const values = readEnv(content);
  const missing = schema.variables
    .filter((v) => v.required !== false && !values[v.name]?.trim())
    .map((v) => v.name);
  if (missing.length)
    fail(
      `${r.name}: required values missing in config/.env: ${missing.join(", ")}; run uppr prepare ${r.name}`,
    );
  protect(
    p,
    ".gitignore",
    "# uppr: local configuration and data\n/config/\n/data/\n",
  );
  protect(
    p,
    ".dockerignore",
    "# uppr: never include runtime state in build context\nconfig/\ndata/\n.git/\n",
  );
  fs.mkdirSync(path.join(p, "config"), { recursive: true, mode: 0o700 });
  fs.mkdirSync(path.join(p, "data"), { recursive: true, mode: 0o700 });
  const db = path.join(p, "data", "main.sqlite");
  if (!exists(db)) fs.writeFileSync(db, "", { mode: 0o600 });
  writeAtomic(env, content, 0o600);
}
export function protect(p: string, file: string, block: string) {
  const target = path.join(p, file);
  let body = exists(target) ? fs.readFileSync(target, "utf8") : "";
  if (!body.includes(block)) {
    if (body && !body.endsWith("\n")) body += "\n";
    fs.writeFileSync(target, body + block);
  }
}
export function prepareRepo(
  root: string,
  r: Repo,
  ask?: (v: Variable) => string,
) {
  const p = repoDir(root, r);
  const schema = readSchema(schemaPath(root, r));
  const env = path.join(p, "config", ".env");
  const content = exists(env) ? fs.readFileSync(env, "utf8") : "";
  const values = readEnv(content);
  const updates: Record<string, string> = {};
  for (const v of schema.variables) {
    if (v.required === false || values[v.name]?.trim()) continue;
    const value = ask?.(v) || "";
    if (value) updates[v.name] = value;
  }
  saveRepoEnv(root, r, updates);
}
export function renderCaddy(m: Manifest) {
  return (
    "# Generated by uppr. Edit launchpad.json, then run uppr generate.\n" +
    sorted(m)
      .map(
        (r) => `\n${r.domain} {\n\treverse_proxy 127.0.0.1:${r.host_port}\n}\n`,
      )
      .join("")
  );
}
export function globalCaddy(
  pads: Record<string, { id: string; root: string }>,
) {
  let body = "# Generated by uppr. Do not edit directly.\n";
  const ports = new Map<number, string>(),
    domains = new Map<string, string>();
  for (const id of Object.keys(pads).sort()) {
    const m = loadManifest(pads[id].root);
    if (m.id !== id) fail(`launchpad ID mismatch at ${pads[id].root}`);
    for (const r of sorted(m)) {
      const label = `${id}/${r.name}`;
      if (ports.has(r.host_port))
        fail(
          `host port ${r.host_port} used by ${ports.get(r.host_port)} and ${label}`,
        );
      if (domains.has(r.domain))
        fail(
          `domain ${r.domain} used by ${domains.get(r.domain)} and ${label}`,
        );
      ports.set(r.host_port, label);
      domains.set(r.domain, label);
      body += `\n${r.domain} {\n\treverse_proxy 127.0.0.1:${r.host_port}\n}\n`;
    }
  }
  return body;
}
export function unitExe(p: string) {
  if (!path.isAbsolute(p) || /[\s"'\\]/.test(p))
    fail(
      `systemd executable path ${p} must be absolute without whitespace or quotes`,
    );
  return p.replaceAll("%", "%%");
}
export function unitQuote(s: string) {
  return JSON.stringify(s.replaceAll("%", "%%"));
}
export function renderUnit(
  root: string,
  bun: string,
  cli: string,
  user: string,
  m: Manifest,
  r: Repo,
) {
  const docker = unitExe(which("docker") || "/usr/bin/docker");
  return `[Unit]\nDescription=Uppr ${m.id} / ${r.name}\nRequires=docker.service\nAfter=docker.service network-online.target\nWants=network-online.target\n\n[Service]\nType=simple\nUser=${user}\nExecStart=${unitExe(bun)} ${unitExe(cli)} run-app ${unitQuote(root)} ${r.name}\nExecStop=-${docker} stop --time 30 ${containerName(m, r)}\nRestart=always\nRestartSec=5\nTimeoutStopSec=40\n\n[Install]\nWantedBy=multi-user.target\n`;
}
export function generate(root: string, m: Manifest) {
  const bun = process.execPath;
  const cli = path.resolve(process.argv[1]);
  const user = os.userInfo().username;
  const dir = path.join(root, "systemd");
  fs.mkdirSync(dir, { recursive: true });
  for (const e of fs.readdirSync(dir))
    if (e.startsWith(`uppr-${m.id}-`) && e.endsWith(".service"))
      fs.rmSync(path.join(dir, e));
  for (const r of sorted(m))
    fs.writeFileSync(
      path.join(dir, unitName(m, r)),
      renderUnit(root, bun, cli, user, m, r),
    );
  fs.writeFileSync(path.join(root, "Caddyfile"), renderCaddy(m));
}
export function renderCaddyUnit(caddy: string) {
  const exe = unitExe(caddy);
  return `[Unit]\nDescription=Uppr shared Caddy reverse proxy\nAfter=network-online.target\nWants=network-online.target\n\n[Service]\nType=notify\nExecStart=${exe} run --environ --config /etc/uppr/Caddyfile --adapter caddyfile\nExecReload=${exe} reload --config /etc/uppr/Caddyfile --adapter caddyfile\nRestart=on-failure\nAmbientCapabilities=CAP_NET_BIND_SERVICE\nEnvironment=XDG_DATA_HOME=/var/lib/uppr/caddy\n\n[Install]\nWantedBy=multi-user.target\n`;
}
export function spawnWait(
  cmd: string,
  args: string[],
  opts: { cwd?: string; env?: NodeJS.ProcessEnv } = {},
) {
  return new Promise<void>((resolve, reject) => {
    const child = spawn(cmd, args, {
      cwd: opts.cwd,
      env: opts.env,
      stdio: "inherit",
    });
    child.on("error", reject);
    child.on("exit", (code) =>
      code === 0 ? resolve() : reject(new Error(`${cmd} exited ${code}`)),
    );
  });
}
