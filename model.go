package main

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const manifestFile = "launchpad.json"

type Manifest struct {
	Version int    `json:"version"`
	ID      string `json:"id"`
	Repos   []Repo `json:"repos"`
}

type Repo struct {
	Name          string `json:"name"`
	URL           string `json:"url"`
	Branch        string `json:"branch,omitempty"`
	Domain        string `json:"domain"`
	HostPort      int    `json:"host_port"`
	ContainerPort int    `json:"container_port"`
}

var safeName = regexp.MustCompile(`^[a-z][a-z0-9-]*$`)

func initPad(path string) error {
	root, err := filepath.Abs(path)
	if err != nil {
		return err
	}
	if _, err := os.Stat(filepath.Join(root, manifestFile)); err == nil {
		return fmt.Errorf("%s is already initialized", root)
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.MkdirAll(filepath.Join(root, "repos"), 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(root, "systemd"), 0o755); err != nil {
		return err
	}
	var bytes [4]byte
	if _, err := rand.Read(bytes[:]); err != nil {
		return err
	}
	base := slug(filepath.Base(root))
	if base == "" {
		base = "pad"
	}
	if base[0] < 'a' || base[0] > 'z' {
		base = "pad-" + base
	}
	m := Manifest{Version: 1, ID: base + "-" + hex.EncodeToString(bytes[:]), Repos: []Repo{}}
	if err := saveManifest(root, m); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, ".gitignore"), []byte("/repos/\n"), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, "Caddyfile"), []byte("# Generated by uppr generate.\n"), 0o644); err != nil {
		return err
	}
	fmt.Println("initialized", root)
	return nil
}

func slug(s string) string {
	s = strings.ToLower(s)
	var out strings.Builder
	for _, r := range s {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			out.WriteRune(r)
		} else if out.Len() > 0 && !strings.HasSuffix(out.String(), "-") {
			out.WriteByte('-')
		}
	}
	return strings.Trim(out.String(), "-")
}

func findPad(start string) (string, Manifest, error) {
	root, err := filepath.Abs(start)
	if err != nil {
		return "", Manifest{}, err
	}
	for {
		m, err := loadManifest(root)
		if err == nil {
			return root, m, nil
		}
		if !errors.Is(err, os.ErrNotExist) {
			return "", Manifest{}, err
		}
		parent := filepath.Dir(root)
		if parent == root {
			return "", Manifest{}, errors.New("launchpad not found; run `uppr init <path>`")
		}
		root = parent
	}
}

func loadManifest(root string) (Manifest, error) {
	data, err := os.ReadFile(filepath.Join(root, manifestFile))
	if err != nil {
		return Manifest{}, err
	}
	var m Manifest
	if err := json.Unmarshal(data, &m); err != nil {
		return m, fmt.Errorf("invalid %s: %w", manifestFile, err)
	}
	if m.Version != 1 || !safeName.MatchString(m.ID) {
		return m, errors.New("unsupported or invalid launchpad manifest")
	}
	seenName, seenPort, seenDomain := map[string]bool{}, map[int]bool{}, map[string]bool{}
	for _, r := range m.Repos {
		if !safeName.MatchString(r.Name) || r.URL == "" || r.HostPort < 1 || r.HostPort > 65535 || r.ContainerPort < 1 || r.ContainerPort > 65535 || r.Domain == "" {
			return m, fmt.Errorf("invalid repo %q in manifest", r.Name)
		}
		if seenName[r.Name] || seenPort[r.HostPort] || seenDomain[r.Domain] {
			return m, fmt.Errorf("duplicate name, host port, or domain for %s", r.Name)
		}
		seenName[r.Name], seenPort[r.HostPort], seenDomain[r.Domain] = true, true, true
	}
	return m, nil
}

func saveManifest(root string, m Manifest) error {
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	tmp, err := os.CreateTemp(root, ".launchpad-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), filepath.Join(root, manifestFile))
}

func repoDir(root string, r Repo) string      { return filepath.Join(root, "repos", r.Name) }
func unitName(m Manifest, r Repo) string      { return "uppr-" + m.ID + "-" + r.Name + ".service" }
func imageName(m Manifest, r Repo) string     { return "uppr-" + m.ID + "-" + r.Name + ":latest" }
func containerName(m Manifest, r Repo) string { return "uppr-" + m.ID + "-" + r.Name }

func selectRepos(m Manifest, name string) ([]Repo, error) {
	if name == "" {
		return m.Repos, nil
	}
	for _, r := range m.Repos {
		if r.Name == name {
			return []Repo{r}, nil
		}
	}
	return nil, fmt.Errorf("unknown repo %q", name)
}

func sortedRepos(m Manifest) []Repo {
	r := append([]Repo(nil), m.Repos...)
	sort.Slice(r, func(i, j int) bool { return r[i].Name < r[j].Name })
	return r
}
